"""Render hostapd, dnsmasq and nftables files from one validated Config.

The Wi-Fi passphrase is never read from the YAML file. It comes from an environment variable at
render time and is written only into hostapd.conf, which is saved with mode 0600.
"""

from __future__ import annotations

import os
from pathlib import Path

from .config import Config

PASSPHRASE_MIN, PASSPHRASE_MAX = 8, 63


class RenderError(ValueError):
    pass


def _header(kind: str) -> str:
    return f"# {kind}: generated by wifi_ap from a YAML file. Edit the YAML and render again.\n"


def render_hostapd(cfg: Config, passphrase: str, accept_file: str) -> str:
    if not PASSPHRASE_MIN <= len(passphrase) <= PASSPHRASE_MAX or "\n" in passphrase:
        raise RenderError(f"the passphrase must be {PASSPHRASE_MIN} to {PASSPHRASE_MAX} characters")
    lines = [
        _header("hostapd"),
        f"interface={cfg.ap_interface}",
        "driver=nl80211",
        f"ssid={cfg.ssid}",
        f"country_code={cfg.country_code}",
        "hw_mode=g",
        f"channel={cfg.channel}",
        "ieee80211n=1",
        "wpa=2",
        "wpa_key_mgmt=WPA-PSK",
        "rsn_pairwise=CCMP",
        f"wpa_passphrase={passphrase}",
        # Only MAC addresses in the accept file may join at all. The rest are refused at association.
        "macaddr_acl=1",
        f"accept_mac_file={accept_file}",
        # Devices on the same access point cannot talk to each other.
        "ap_isolate=1",
    ]
    return "\n".join(lines) + "\n"


def render_accept_file(cfg: Config) -> str:
    return "".join(f"{dev.mac}\n" for dev in cfg.devices)


def render_dnsmasq(cfg: Config, state_dir: str) -> str:
    lines = [
        _header("dnsmasq"),
        f"interface={cfg.ap_interface}",
        "bind-interfaces",
        "port=0",  # DNS is off. The devices only need DHCP and a sensor IP address.
        "no-resolv",
        "no-hosts",
        f"dhcp-range={cfg.dhcp_start},{cfg.dhcp_end},{cfg.lease_time}",
        f"dhcp-option=option:router,{cfg.gateway}",
        "dhcp-authoritative",
        f"dhcp-leasefile={state_dir}/dnsmasq.leases",
        f"pid-file={state_dir}/dnsmasq.pid",
    ]
    for dev in cfg.devices:
        lines.append(f"dhcp-host={dev.mac},{dev.ip},{dev.name},set:known")
    if cfg.only_known_devices:
        lines.append("dhcp-ignore=tag:!known")
    return "\n".join(lines) + "\n"


def render_nftables(cfg: Config) -> str:
    """Isolation rules. Devices may reach the sensor endpoint and nothing else on the home network."""
    subnet = cfg.subnet
    ap, up = cfg.ap_interface, cfg.uplink_interface
    return f"""{_header("nftables")}table inet wifi_ap
delete table inet wifi_ap
table inet wifi_ap {{
  chain input {{
    # Only the AP host itself is affected: the input policy stays accept for other interfaces.
    type filter hook input priority filter; policy accept;
    iifname "{ap}" udp dport 67 accept
    iifname "{ap}" drop
  }}
  chain forward {{
    # Forwarding is closed by default, so the devices cannot reach any home address by accident.
    type filter hook forward priority filter; policy drop;
    ct state established,related accept
    iifname "{ap}" oifname "{up}" ip daddr {cfg.sensor_ip} tcp dport {cfg.sensor_port} accept
  }}
}}
table ip wifi_ap_nat {{
  chain postrouting {{
    type nat hook postrouting priority srcnat; policy accept;
    # The home network only sees this box's uplink address, never a device address.
    oifname "{up}" ip saddr {subnet} masquerade
  }}
}}
"""


def render_all(cfg: Config, passphrase: str, out_dir: str | Path, state_dir: str) -> dict[str, Path]:
    """Write hostapd.conf (mode 0600), hostapd.accept, dnsmasq.conf and nftables.nft into out_dir."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    accept_path = out / "hostapd.accept"
    files = {
        "hostapd.conf": render_hostapd(cfg, passphrase, str(accept_path)),
        "hostapd.accept": render_accept_file(cfg),
        "dnsmasq.conf": render_dnsmasq(cfg, state_dir),
        "nftables.nft": render_nftables(cfg),
    }
    written: dict[str, Path] = {}
    for name, text in files.items():
        path = out / name
        mode = 0o600 if name == "hostapd.conf" else 0o644
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, mode)
        with os.fdopen(fd, "w") as handle:
            handle.write(text)
        os.chmod(path, mode)
        written[name] = path
    return written


def passphrase_from_env(var: str = "WIFI_AP_PASSPHRASE") -> str:
    value = os.environ.get(var, "")
    if not value:
        raise RenderError(f"set {var} in the environment; it is never stored in the YAML file")
    return value
